/* ---------- Apply to pages ---------- */
const SKIP = new Set(['why-telaqua.html']);
const pages = fs.readdirSync(root).filter(f => f.endsWith('.html') && !SKIP.has(f));
const HEAD_TAGS = `<!-- GA-HEAD -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap" rel="stylesheet">
<link rel="stylesheet" href="css/apple.css?v=1">
<!-- /GA-HEAD -->`;
const SCRIPT_TAG = '<script src="js/apple-nav.js?v=1" defer></script>';

const replaceBlock = (html, start, end, block) => {
  const re = new RegExp(`<!-- ${start}[\\s\\S]*?<!-- ${end} -->`);
  return re.test(html) ? html.replace(re, block) : null;
};

for(const file of pages){
  const fp = path.join(root, file);
  let html = fs.readFileSync(fp, 'utf8');
  const before = html;

  // NAV
  const nav = navHtml();
  let next = replaceBlock(html, 'GA-NAV:START', 'GA-NAV:END', nav);
  if(next === null){
    const withChrome = /<div class="site-chrome">\s*<header class="navbar">[\s\S]*?<\/header>\s*<\/div>/;
    const plain = /<header class="navbar">[\s\S]*?<\/header>/;
    if(withChrome.test(html)) next = html.replace(withChrome, nav);
    else if(plain.test(html)) next = html.replace(plain, nav);
    else next = html.replace(/(<body[^>]*>)/, `$1\n${nav}`);
  }
  html = next;

  // FOOTER
  const foot = footerHtml();
  next = replaceBlock(html, 'GA-FOOTER:START', 'GA-FOOTER:END', foot);
  if(next === null){
    const legacy = /<footer class="site-footer">[\s\S]*?<\/footer>/;
    next = legacy.test(html) ? html.replace(legacy, foot) : html.replace(/(<script[^>]*src=)/, `${foot}\n\n$1`);
  }
  html = next;

  // HEAD
  if(!html.includes('<!-- GA-HEAD -->')) html = html.replace('</head>', `${HEAD_TAGS}\n</head>`);
  // SCRIPT
  if(!html.includes('js/apple-nav.js')) html = html.replace(/<\/body>(?![\s\S]*<\/body>)/, `${SCRIPT_TAG}\n</body>`);

  if(html !== before){ fs.writeFileSync(fp, html); console.log('updated', file); }
  else console.log('unchanged', file);
}
